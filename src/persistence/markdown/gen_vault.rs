//! Generate `vault.rs`: `open_vault`, the one constructor for the consumer's
//! `markdown_store::VaultHandle`, built from the same configuration the rest
//! of the markdown output comes from. Consumers call it instead of repeating
//! the layout, id strategy, list cap and OKF options by hand.

use crate::MarkdownIoConfig;
use crate::ir::{IdStrategy, MarkdownLayout};

/// The module name `vault.rs` is emitted under, beside the per-entity
/// frontmatter modules.
pub(crate) const VAULT_MODULE: &str = "vault";

/// Generate the `vault.rs` source for `config`.
pub fn generate_vault_module(config: &MarkdownIoConfig) -> String {
    let layout = match config.layout {
        MarkdownLayout::PerEntityDir => "PerEntityDir",
        MarkdownLayout::Flat => "Flat",
    };
    let id_strategy = match &config.id_strategy {
        IdStrategy::Provided => "markdown_store::IdStrategy::Provided".to_string(),
        IdStrategy::SlugFromField(field) => format!("markdown_store::IdStrategy::SlugFromField({field:?}.into())"),
        IdStrategy::Uuid => "markdown_store::IdStrategy::Uuid".to_string(),
    };

    let mut code = String::with_capacity(1024);
    code.push_str("//! Generated by ontogen. DO NOT EDIT.\n\n");
    code.push_str(
        "/// Where the vault's records live, relative to the crate root, as configured\n\
         /// at build time.\n",
    );
    code.push_str(&format!("pub const VAULT_ROOT: &str = {:?};\n\n", config.vault_root.to_string_lossy()));
    code.push_str(
        "/// Open the vault at `root` with the layout, id strategy, list cap and OKF\n\
         /// options configured at build time. Pass [`VAULT_ROOT`] to use the configured\n\
         /// location, or any other directory (a test's tempdir, say).\n",
    );
    code.push_str("pub fn open_vault(root: impl Into<std::path::PathBuf>) -> markdown_store::VaultHandle {\n");
    code.push_str(&format!(
        "    markdown_store::VaultHandle::new(root, markdown_store::VaultLayout::{layout}, {id_strategy})\n"
    ));
    code.push_str(&format!("        .with_list_cap({})\n", config.list_cap));
    code.push_str(&format!("        .with_okf_index({})\n", config.okf.index));
    if let Some(actor) = &config.okf.generated_by {
        code.push_str(&format!("        .with_generated_by({actor:?})\n"));
    }
    code.push_str("}\n");
    code
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::OkfOptions;

    fn config(okf: OkfOptions) -> MarkdownIoConfig {
        MarkdownIoConfig {
            output_dir: "unused".into(),
            vault_root: "data/vault".into(),
            layout: MarkdownLayout::PerEntityDir,
            id_strategy: IdStrategy::SlugFromField("title".into()),
            list_cap: 10_000,
            okf,
        }
    }

    #[test]
    fn open_vault_applies_the_configuration() {
        let code = generate_vault_module(&config(OkfOptions::default()));
        assert!(code.contains("pub const VAULT_ROOT: &str = \"data/vault\";"), "{code}");
        assert!(
            code.contains(
                "markdown_store::VaultHandle::new(root, markdown_store::VaultLayout::PerEntityDir, \
                 markdown_store::IdStrategy::SlugFromField(\"title\".into()))"
            ),
            "{code}"
        );
        assert!(code.contains(".with_list_cap(10000)"), "{code}");
        assert!(code.contains(".with_okf_index(false)"), "{code}");
        assert!(!code.contains("with_generated_by"), "no stamping unless configured: {code}");
        syn::parse_file(&code).expect("valid Rust");
    }

    #[test]
    fn okf_options_thread_into_open_vault() {
        let code =
            generate_vault_module(&config(OkfOptions { index: true, generated_by: Some("notes-kb/0.1.0".into()) }));
        assert!(code.contains(".with_okf_index(true)\n        .with_generated_by(\"notes-kb/0.1.0\")\n}"), "{code}");
        syn::parse_file(&code).expect("valid Rust");
    }

    #[test]
    fn every_layout_and_id_strategy_maps_to_its_runtime_variant() {
        let mut flat = config(OkfOptions::default());
        flat.layout = MarkdownLayout::Flat;
        flat.id_strategy = IdStrategy::Uuid;
        let code = generate_vault_module(&flat);
        assert!(code.contains("markdown_store::VaultLayout::Flat, markdown_store::IdStrategy::Uuid)"), "{code}");

        flat.id_strategy = IdStrategy::Provided;
        assert!(generate_vault_module(&flat).contains("markdown_store::IdStrategy::Provided)"));
    }
}
