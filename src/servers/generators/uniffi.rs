#![allow(clippy::format_push_string)]

//! Generate a UniFFI export of the API, for native (Swift, Kotlin, ...) apps.
//!
//! EXPERIMENTAL. The output is one Rust module, compiled into the consuming
//! crate, that UniFFI turns into foreign-language bindings:
//!
//! - `NativeApi`, a `uniffi::Object` holding the app state and a tokio
//!   runtime handle, with one async method per API fn named as its IPC
//!   command (`workout_list`, which Swift calls as `workoutList`). Each call
//!   runs on that runtime, so the store's I/O stays on the runtime that owns
//!   it whichever thread the foreign side polls from.
//! - A `#[uniffi::remote(Record)]` / `#[uniffi::remote(Enum)]` mirror of
//!   every type the API's signatures reach, found by scanning the crate's
//!   `src/` the way the TypeScript bindings are. A mirror restates the
//!   type's fields and implements the FFI traits for it, so the consumer's
//!   types carry no UniFFI attributes. A type that already derives a UniFFI
//!   trait is used as it is.
//! - `ApiError`, the one error every method throws: the `code` the HTTP
//!   transport gives the failure, and its message.
//! - Per event op, a `{Fn}Subscription` object whose `next()` yields
//!   `{Item}Frame`s (`Event` or `Lag`) and `None` once the feed closes.
//! - Per paginated item type, an `{Item}Page` record.
//!
//! The consumer calls `uniffi::setup_scaffolding!()` at its crate root and
//! exports a constructor that builds `NativeApi::new(state, runtime)`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use ontogen_core::ir::OpKind;
use syn::{Fields, Item};

use crate::servers::classify::classify_op;
use crate::servers::config::Config;
use crate::servers::generators::http::{event_returns_app_error, returns_app_error};
use crate::servers::generators::ipc::command_name;
use crate::servers::generators::{filter_arg, surface_use_stmts_where};
use crate::servers::parse::{ApiFn, ApiModule, EventFn, Param};
use crate::servers::types::{
    capitalize, collect_type_import, extract_input_type, forward_arg_expr, inner_type, norm_tokens, norm_type,
    param_to_owned_type, snake_to_camel,
};

/// The exported object's name.
const OBJECT: &str = "NativeApi";

/// Generate the UniFFI module and write it to `output`.
///
/// `src_dir` is the consuming crate's `src/`, scanned for the definitions of
/// the types the API exposes.
///
/// # Errors
///
/// When the configuration uses what this generator does not support yet
/// (a route prefix), or when an exposed type cannot be mirrored: it is not
/// defined in the crate, is ambiguous, or has a shape UniFFI cannot carry.
pub fn generate(output: &Path, src_dir: &Path, modules: &[ApiModule], config: &Config) -> Result<(), String> {
    if config.route_prefix.is_some() {
        return Err("ontogen: the Uniffi generator does not support `route_prefix` yet".to_string());
    }

    let types = TypeClosure::build(src_dir, output, modules, config)?;

    let mut body = String::new();
    let mut pages: BTreeSet<String> = BTreeSet::new();
    let mut frames: BTreeSet<String> = BTreeSet::new();

    body.push_str(&format!("#[uniffi::export]\nimpl {OBJECT} {{\n"));
    for m in modules {
        for f in &m.functions {
            if matches!(classify_op(m, f), OpKind::EventStream) {
                continue;
            }
            body.push_str(&method(m, f, config, &mut pages));
        }
        for ev in &m.events {
            body.push_str(&subscribe_method(m, ev, config));
            frames.insert(ev.item_type.clone());
        }
    }
    body.push_str("}\n\n");

    for m in modules {
        for ev in &m.events {
            body.push_str(&subscription_object(ev));
        }
    }
    for item in &frames {
        body.push_str(&frame_enum(item));
    }
    for item in &pages {
        body.push_str(&page_record(item));
    }
    for mirror in &types.mirrors {
        body.push_str(&mirror.render()?);
    }

    let mut out = String::from(
        "\
#![allow(dead_code, unused_imports, clippy::pedantic, clippy::needless_borrow)]
//! Auto-generated UniFFI export of the API. DO NOT EDIT. EXPERIMENTAL.
//!
//! Generated by ontogen from API source files.

use std::sync::Arc;

",
    );
    let mut use_stmts = surface_use_stmts_where(modules, config, &|_| false);
    use_stmts.push(format!("use {};\n", config.state_import));
    let mut by_module: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for path in &types.imports {
        let (module, name) = path.rsplit_once("::").unwrap_or(("crate", path));
        by_module.entry(module).or_default().push(name);
    }
    use_stmts.extend(by_module.iter().map(|(module, names)| format!("use {module}::{{{}}};\n", names.join(", "))));
    use_stmts.sort();
    use_stmts.dedup();
    for stmt in &use_stmts {
        out.push_str(stmt);
    }
    out.push('\n');
    out.push_str(&prelude(config));
    out.push_str(&body);

    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("ontogen: failed to create {}: {e}", parent.display()))?;
    }
    crate::write_and_format(output, out).map_err(|e| format!("ontogen: failed to write the UniFFI module: {e}"))
}

/// The error type, its mapping helpers, and the object with its runner.
fn prelude(config: &Config) -> String {
    let state = config.state_import.rsplit("::").next().unwrap_or(&config.state_type);
    let mut out = String::from(
        "\
/// The error every native call throws: the `code` the HTTP transport gives
/// the same failure, and a message for people.
#[derive(Debug, uniffi::Error)]
pub enum ApiError {
    Failed { code: String, message: String },
}

impl std::fmt::Display for ApiError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ApiError::Failed { code, message } => write!(f, \"{code}: {message}\"),
        }
    }
}

impl std::error::Error for ApiError {}

",
    );
    match &config.error_map {
        Some(map) => {
            let path = format!("{}::AppError", config.types_import_path);
            out.push_str(&format!(
                "/// An `AppError` as an `ApiError`, coded by its variant's name in snake_case.\n\
                 pub(crate) fn ontogen_app_error(e: {path}) -> ApiError {{\n    let code = match &e {{\n"
            ));
            for v in &map.variants {
                out.push_str(&format!("        {} => \"{}\",\n", v.pattern(&path), v.code));
            }
            out.push_str("    };\n    ApiError::Failed { code: code.to_string(), message: e.to_string() }\n}\n\n");
        }
        None => out.push_str(
            "\
/// No `AppError` was found in the schema directory, so every error is `internal`.
pub(crate) fn ontogen_app_error(e: impl std::fmt::Display) -> ApiError {
    ontogen_internal_error(e)
}

",
        ),
    }
    out.push_str(&format!(
        "\
/// A failure no `AppError` describes: opening the store, a lost task, or an
/// op with another error type.
fn ontogen_internal_error(e: impl std::fmt::Display) -> ApiError {{
    ApiError::Failed {{ code: \"internal\".to_string(), message: e.to_string() }}
}}

/// A `sort` key the list's order does not have.
fn ontogen_sort_error(e: impl std::fmt::Display) -> ApiError {{
    ApiError::Failed {{ code: \"invalid_sort_field\".to_string(), message: e.to_string() }}
}}

/// The API, exported to the foreign side. Build it with [`{OBJECT}::new`]
/// from the consumer's own exported constructor.
#[derive(uniffi::Object)]
pub struct {OBJECT} {{
    state: Arc<{state}>,
    runtime: tokio::runtime::Handle,
}}

impl {OBJECT} {{
    /// The API over `state`, running every call on `runtime`.
    pub fn new(state: Arc<{state}>, runtime: tokio::runtime::Handle) -> Arc<Self> {{
        Arc::new(Self {{ state, runtime }})
    }}

    /// Run `f` on the API's runtime. The foreign side polls the returned
    /// future from its own executor; the work itself never leaves the runtime.
    async fn ontogen_run<T, F, Fut>(&self, f: F) -> Result<T, ApiError>
    where
        F: FnOnce(Arc<{state}>) -> Fut,
        Fut: std::future::Future<Output = Result<T, ApiError>> + Send + 'static,
        T: Send + 'static,
    {{
        self.runtime.spawn(f(self.state.clone())).await.map_err(ontogen_internal_error)?
    }}
}}

"
    ));
    out
}

/// The first argument a fn takes and the line that obtains it, as
/// (`setup`, `Some(arg)`), or `(\"\", None)` for a stateless fn.
fn state_arg(f: &ApiFn) -> (String, Option<&'static str>) {
    if f.is_stateless {
        (String::new(), None)
    } else if f.first_param_is_store {
        (
            format!(
                "let ontogen_store = ontogen_state.{}().await.map_err(ontogen_internal_error)?;\n",
                f.store_accessor
            ),
            Some("&ontogen_store"),
        )
    } else {
        (String::new(), Some("&ontogen_state"))
    }
}

fn doc_lines(doc: &str, indent: &str) -> String {
    doc.lines().map(|l| format!("{indent}/// {}\n", l.trim())).collect()
}

/// The `{Item}Page` record name for a paginated list of `item`.
fn page_name(item: &str) -> String {
    format!("{}Page", type_ident(item))
}

/// The `{Item}Frame` enum name for an event feed of `item`.
fn frame_name(item: &str) -> String {
    format!("{}Frame", type_ident(item))
}

/// A type rendered as an identifier fragment: `Vec<Foo>` → `VecFoo`.
fn type_ident(ty: &str) -> String {
    ty.split(|c: char| !c.is_alphanumeric()).filter(|s| !s.is_empty()).map(capitalize).collect()
}

/// One API fn as a method of the exported object.
fn method(m: &ApiModule, f: &ApiFn, config: &Config, pages: &mut BTreeSet<String>) -> String {
    let op = classify_op(m, f);
    let svc = m.service_ident(f.surface);
    let name = command_name(&m.name, f, config);
    let await_str = if f.is_async { ".await" } else { "" };
    let err = if returns_app_error(f, config) { "ontogen_app_error" } else { "ontogen_internal_error" };
    let (setup, first_arg) = state_arg(f);
    let paginated = config.pagination_for(&m.name, f.surface).filter(|_| f.return_type.starts_with("Vec<"));

    let mut params: Vec<String> = Vec::new();
    let mut body = setup;
    let ret: String;

    if matches!(op, OpKind::List) {
        // As over IPC: a `*Query` struct as `query`, bare filters under their
        // own names, `sort` for the order, and `limit`/`offset` for a page.
        let binding = |p: &Param| if p.is_filter_struct() { "query".to_string() } else { p.name.clone() };
        if let Some(qp) = f.filter_struct() {
            params.push(format!("query: {}", extract_input_type(&qp.ty)));
        }
        for p in f.bare_filters() {
            params.push(format!("{}: {}", p.name, param_to_owned_type(&p.ty_ast)));
        }
        let order_arg = if f.takes_order() {
            params.push("sort: Option<Vec<String>>".to_string());
            body.push_str(
                "let ontogen_order = ontogen_core::order::parse_sort(sort.unwrap_or_default()).map_err(ontogen_sort_error)?;\n",
            );
            ", &ontogen_order"
        } else {
            ""
        };
        let filter_args = |counted: bool| -> String {
            f.filter().iter().map(|p| format!(", {}", filter_arg(p, &binding(p), counted))).collect()
        };
        let first = first_arg.unwrap_or_default();
        if let Some(pg) = paginated {
            let item = inner_type(&f.return_type);
            params.push("limit: Option<u32>".to_string());
            params.push("offset: Option<u32>".to_string());
            body.push_str(&format!(
                "let ontogen_limit = limit.unwrap_or({}).min({});\n\
                 let ontogen_offset = offset.unwrap_or(0);\n\
                 let ontogen_items = {svc}::list({first}{}{order_arg}, Some(u64::from(ontogen_limit)), Some(u64::from(ontogen_offset))){await_str}.map_err({err})?;\n\
                 let ontogen_total = {svc}::count({first}{}){await_str}.map_err({err})?;\n\
                 Ok({} {{ items: ontogen_items, total: ontogen_total, limit: ontogen_limit, offset: ontogen_offset }})\n",
                pg.default_limit,
                pg.max_limit,
                filter_args(true),
                filter_args(false),
                page_name(&item),
            ));
            ret = page_name(&item);
            pages.insert(item);
        } else {
            let page_args = if f.takes_page() { ", None, None" } else { "" };
            body.push_str(&format!(
                "{svc}::list({first}{}{order_arg}{page_args}){await_str}.map_err({err})\n",
                filter_args(false)
            ));
            ret = f.return_type.clone();
        }
    } else {
        for p in &f.params {
            params.push(format!("{}: {}", p.name, param_to_owned_type(&p.ty_ast)));
        }
        let args: Vec<String> = first_arg
            .map(str::to_string)
            .into_iter()
            .chain(f.params.iter().map(|p| forward_arg_expr(&p.name, &p.ty_ast)))
            .collect();
        let call = format!("{svc}::{}({}){await_str}", f.name, args.join(", "));
        if let (Some(pg), OpKind::JunctionList { .. }) = (paginated, &op) {
            // A junction list pages in memory, as over IPC.
            let item = inner_type(&f.return_type);
            params.push("limit: Option<u32>".to_string());
            params.push("offset: Option<u32>".to_string());
            body.push_str(&format!(
                "let ontogen_all = {call}.map_err({err})?;\n\
                 let ontogen_total = ontogen_all.len() as u64;\n\
                 let ontogen_limit = limit.unwrap_or({}).min({});\n\
                 let ontogen_offset = offset.unwrap_or(0);\n\
                 let ontogen_items = ontogen_all.into_iter().skip(ontogen_offset as usize).take(ontogen_limit as usize).collect();\n\
                 Ok({} {{ items: ontogen_items, total: ontogen_total, limit: ontogen_limit, offset: ontogen_offset }})\n",
                pg.default_limit,
                pg.max_limit,
                page_name(&item),
            ));
            ret = page_name(&item);
            pages.insert(item);
        } else {
            body.push_str(&format!("{call}.map_err({err})\n"));
            ret = f.return_type.clone();
        }
    }

    let state_binding = if f.is_stateless { "_ontogen_state" } else { "ontogen_state" };
    let params: String = params.iter().map(|p| format!(", {p}")).collect();
    format!(
        "{}    pub async fn {name}(&self{params}) -> Result<{ret}, ApiError> {{\n\
         self.ontogen_run(move |{state_binding}| async move {{\n{body}}}).await\n\
         }}\n\n",
        doc_lines(&f.doc, "    "),
    )
}

/// The subscription object an event op's subscribe method returns.
fn subscription_name(ev: &EventFn) -> String {
    format!("{}Subscription", capitalize(&snake_to_camel(&ev.name)))
}

/// An event op as a `{fn}_subscribe` method returning its subscription.
fn subscribe_method(m: &ApiModule, ev: &EventFn, config: &Config) -> String {
    let svc = m.service_ident(ev.surface);
    let sub = subscription_name(ev);
    let await_str = if ev.is_async { ".await" } else { "" };
    let err = if event_returns_app_error(ev, config) { "ontogen_app_error" } else { "ontogen_internal_error" };
    let map_err = if ev.returns_result { format!(".map_err({err})?") } else { String::new() };
    let id_fn = if ev.is_resumable() { "ontogen_core::events::seq_id" } else { "ontogen_core::events::no_id" };
    let params: String =
        ev.params.iter().map(|p| format!(", {}: {}", p.name, param_to_owned_type(&p.ty_ast))).collect();
    let args: String = ev.params.iter().map(|p| format!(", {}", forward_arg_expr(&p.name, &p.ty_ast))).collect();
    format!(
        "{}    pub async fn {}_subscribe(&self{params}) -> Result<Arc<{sub}>, ApiError> {{\n\
         let ontogen_runtime = self.runtime.clone();\n\
         self.ontogen_run(move |ontogen_state| async move {{\n\
         let ontogen_rx = {svc}::{}(&ontogen_state{args}){await_str}{map_err};\n\
         Ok(Arc::new({sub} {{ rx: Arc::new(tokio::sync::Mutex::new(ontogen_rx)), id: {id_fn}, runtime: ontogen_runtime }}))\n\
         }}).await\n\
         }}\n\n",
        doc_lines(&ev.doc, "    "),
        ev.name,
        ev.name,
    )
}

fn subscription_object(ev: &EventFn) -> String {
    let sub = subscription_name(ev);
    let item = &ev.item_type;
    let frame = frame_name(item);
    format!(
        "\
/// A live `{name}` feed. Call `next()` until it returns `None`.
#[derive(uniffi::Object)]
pub struct {sub} {{
    rx: Arc<tokio::sync::Mutex<tokio::sync::broadcast::Receiver<{item}>>>,
    id: ontogen_core::events::IdFn<{item}>,
    runtime: tokio::runtime::Handle,
}}

#[uniffi::export]
impl {sub} {{
    /// The next frame: an event, or how many events were dropped because
    /// this subscriber fell behind. `None` once the feed closes.
    pub async fn next(&self) -> Option<{frame}> {{
        let rx = self.rx.clone();
        let id = self.id;
        self.runtime
            .spawn(async move {{
                let mut rx = rx.lock().await;
                ontogen_core::events::next_frame(&mut rx, id).await.map({frame}::from)
            }})
            .await
            .ok()
            .flatten()
    }}
}}

",
        name = ev.name,
    )
}

fn frame_enum(item: &str) -> String {
    let frame = frame_name(item);
    format!(
        "\
/// One message on an event feed of `{item}`.
#[derive(uniffi::Enum)]
pub enum {frame} {{
    /// An item, with its resume id when the feed is resumable.
    Event {{ id: Option<String>, data: {item} }},
    /// The subscriber fell behind and `skipped` items were dropped.
    Lag {{ skipped: u64 }},
}}

impl From<ontogen_core::events::EventFrame<{item}>> for {frame} {{
    fn from(frame: ontogen_core::events::EventFrame<{item}>) -> Self {{
        match frame {{
            ontogen_core::events::EventFrame::Event {{ id, data }} => {frame}::Event {{ id, data }},
            ontogen_core::events::EventFrame::Lag {{ skipped }} => {frame}::Lag {{ skipped }},
        }}
    }}
}}

"
    )
}

fn page_record(item: &str) -> String {
    format!(
        "\
/// One page of a paginated `{item}` list.
#[derive(uniffi::Record)]
pub struct {page} {{
    pub items: Vec<{item}>,
    pub total: u64,
    pub limit: u32,
    pub offset: u32,
}}

",
        page = page_name(item),
    )
}

// ── Type closure ─────────────────────────────────────────────────────────────

/// A type the API exposes that the generated module mirrors for UniFFI.
struct Mirror {
    /// The bare name it is imported under.
    name: String,
    item: Item,
}

impl Mirror {
    /// The `#[uniffi::remote(..)]` restatement of the type.
    fn render(&self) -> Result<String, String> {
        let unsupported = |what: &str| {
            Err(format!(
                "ontogen: the Uniffi generator cannot mirror `{}`: {what}. Derive a UniFFI trait on it yourself, or \
                 keep it out of the API's signatures",
                self.name
            ))
        };
        let mut out = String::new();
        match &self.item {
            Item::Struct(s) => {
                if !s.generics.params.is_empty() {
                    return unsupported("UniFFI records cannot be generic");
                }
                let Fields::Named(fields) = &s.fields else {
                    return unsupported("UniFFI records need named fields");
                };
                out.push_str(&docs(&s.attrs, ""));
                out.push_str(&format!("#[uniffi::remote(Record)]\npub struct {} {{\n", s.ident));
                for field in &fields.named {
                    let ident = field.ident.as_ref().expect("named field");
                    out.push_str(&docs(&field.attrs, "    "));
                    out.push_str(&format!("    pub {ident}: {},\n", norm_type(&field.ty)));
                }
                out.push_str("}\n\n");
            }
            Item::Enum(e) => {
                if !e.generics.params.is_empty() {
                    return unsupported("UniFFI enums cannot be generic");
                }
                out.push_str(&docs(&e.attrs, ""));
                out.push_str(&format!("#[uniffi::remote(Enum)]\npub enum {} {{\n", e.ident));
                for v in &e.variants {
                    out.push_str(&docs(&v.attrs, "    "));
                    match &v.fields {
                        Fields::Unit => out.push_str(&format!("    {},\n", v.ident)),
                        Fields::Unnamed(fields) => {
                            let tys: Vec<String> = fields.unnamed.iter().map(|f| norm_type(&f.ty)).collect();
                            out.push_str(&format!("    {}({}),\n", v.ident, tys.join(", ")));
                        }
                        Fields::Named(fields) => {
                            let fs: Vec<String> = fields
                                .named
                                .iter()
                                .map(|f| format!("{}: {}", f.ident.as_ref().expect("named field"), norm_type(&f.ty)))
                                .collect();
                            out.push_str(&format!("    {} {{ {} }},\n", v.ident, fs.join(", ")));
                        }
                    }
                }
                out.push_str("}\n\n");
            }
            _ => return unsupported("only structs and enums can cross the FFI"),
        }
        Ok(out)
    }
}

/// The `///` lines of an item's doc attributes.
fn docs(attrs: &[syn::Attribute], indent: &str) -> String {
    attrs
        .iter()
        .filter(|a| a.path().is_ident("doc"))
        .filter_map(|a| match &a.meta {
            syn::Meta::NameValue(nv) => match &nv.value {
                syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) => Some(s.value()),
                _ => None,
            },
            _ => None,
        })
        .map(|line| format!("{indent}///{line}\n"))
        .collect()
}

/// True when the item already derives or is annotated with a UniFFI trait.
fn has_uniffi_attr(item: &Item) -> bool {
    let attrs = match item {
        Item::Struct(s) => &s.attrs,
        Item::Enum(e) => &e.attrs,
        _ => return false,
    };
    attrs.iter().any(|a| norm_tokens(&a.meta).contains("uniffi"))
}

/// The module path, below the crate root, of the file this generator writes.
/// `None` when that file doesn't exist yet or lives outside `src_dir`.
fn own_module(src_dir: &Path, output: &Path) -> Option<Vec<String>> {
    let output = output.canonicalize().ok()?;
    let relative = output.strip_prefix(src_dir.canonicalize().ok()?).ok()?.with_extension("");
    let mut path: Vec<String> = relative.iter().map(|part| part.to_string_lossy().into_owned()).collect();
    if path.last().is_some_and(|last| last == "mod") {
        path.pop();
    }
    Some(path)
}

/// Every type the API's signatures reach, with the import each needs.
struct TypeClosure {
    mirrors: Vec<Mirror>,
    /// Import paths for every exposed type, mirrored or not.
    imports: BTreeSet<String>,
}

impl TypeClosure {
    fn build(src_dir: &Path, output: &Path, modules: &[ApiModule], config: &Config) -> Result<Self, String> {
        let (mut pool, imports) = ontogen_ts::scan_src_dir_with_imports(src_dir)
            .map_err(|e| format!("ontogen: the Uniffi generator could not scan {}: {e}", src_dir.display()))?;
        // The last build's output is in `src/` too, and its mirrors must not
        // count as definitions of the types they mirror.
        if let Some(own) = own_module(src_dir, output) {
            pool.retain(|key, _| !key.segments().get(1..).is_some_and(|path| path.starts_with(&own)));
        }
        let surfaces = config.surfaces();

        // Roots: the bare type names in every signature, read from the
        // surface's types module as the other transports import them.
        let mut roots: Vec<(String, usize)> = Vec::new();
        for m in modules {
            for f in &m.functions {
                let mut names = Vec::new();
                collect_type_import(&f.return_type_ast, &mut names);
                for p in f.params.iter().filter(|p| p.order_sort_field().is_none()) {
                    collect_type_import(&p.ty_ast, &mut names);
                }
                roots.extend(names.into_iter().map(|n| (n, f.surface)));
            }
            for ev in &m.events {
                let mut names = Vec::new();
                collect_type_import(&ev.item_type_ast, &mut names);
                for p in &ev.params {
                    collect_type_import(&p.ty_ast, &mut names);
                }
                roots.extend(names.into_iter().map(|n| (n, ev.surface)));
            }
        }

        let mut closure = Self { mirrors: Vec::new(), imports: BTreeSet::new() };
        // Pool key → the name it was imported under, to refuse two types
        // that share a name.
        let mut seen: BTreeMap<ontogen_ts::TypePath, String> = BTreeMap::new();
        let mut errors: Vec<String> = Vec::new();
        let mut queue: Vec<(String, Vec<String>, Option<String>)> = Vec::new();

        for (name, surface) in roots {
            let types_path = &surfaces[surface].types_import_path;
            let module: Vec<String> = types_path.split("::").map(str::to_string).collect();
            queue.push((name.clone(), module, Some(format!("{types_path}::{name}"))));
        }

        while let Some((name, module, import)) = queue.pop() {
            let key = match ontogen_ts::resolve_reference(std::slice::from_ref(&name), &module, &pool, &imports) {
                ontogen_ts::Resolution::Resolved(key) => key,
                ontogen_ts::Resolution::NotInPool => {
                    errors.push(format!(
                        "`{name}` is not defined in this crate, so it cannot be mirrored (an external type needs a \
                         `uniffi::custom_type!`)"
                    ));
                    continue;
                }
                ontogen_ts::Resolution::Ambiguous(candidates) => {
                    let candidates: Vec<String> = candidates.iter().map(|c| c.segments().join("::")).collect();
                    errors.push(format!("`{name}` is ambiguous: {}", candidates.join(", ")));
                    continue;
                }
            };
            if let Some(prior) = seen.get(&key) {
                if *prior != name {
                    errors.push(format!("`{}` is reached as both `{prior}` and `{name}`", key.segments().join("::")));
                }
                continue;
            }
            if seen.values().any(|n| *n == name) {
                errors.push(format!("two different types named `{name}` cross the FFI"));
                continue;
            }
            seen.insert(key.clone(), name.clone());

            // A type is imported where the signatures found it, else through
            // a types module that re-exports it, else by its defining path,
            // which must then be visible from the generated module.
            let import = import
                .or_else(|| {
                    surfaces.iter().map(|s| &s.types_import_path).find_map(|types_path| {
                        let module: Vec<String> = types_path.split("::").map(str::to_string).collect();
                        let found =
                            ontogen_ts::resolve_reference(std::slice::from_ref(&name), &module, &pool, &imports);
                        matches!(found, ontogen_ts::Resolution::Resolved(k) if k == key)
                            .then(|| format!("{types_path}::{name}"))
                    })
                })
                .unwrap_or_else(|| key.segments().join("::"));
            closure.imports.insert(import);

            let Some(item) = pool.get(&key) else { continue };
            if has_uniffi_attr(item) {
                continue;
            }
            let item_module: Vec<String> = key.segments()[..key.segments().len() - 1].to_vec();
            for ty in field_types(item) {
                let mut names = Vec::new();
                collect_type_import(ty, &mut names);
                for n in names {
                    queue.push((n, item_module.clone(), None));
                }
            }
            closure.mirrors.push(Mirror { name, item: item.clone() });
        }

        if !errors.is_empty() {
            errors.sort();
            errors.dedup();
            return Err(format!("ontogen: the Uniffi generator cannot export the API:\n  - {}", errors.join("\n  - ")));
        }
        closure.mirrors.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(closure)
    }
}

/// The types of every field of a struct or enum.
fn field_types(item: &Item) -> Vec<&syn::Type> {
    match item {
        Item::Struct(s) => s.fields.iter().map(|f| &f.ty).collect(),
        Item::Enum(e) => e.variants.iter().flat_map(|v| v.fields.iter().map(|f| &f.ty)).collect(),
        _ => Vec::new(),
    }
}
