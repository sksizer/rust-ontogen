/// A tool's input schema: `base` (a `schema_for::<T>` path), with the
/// scope's argument when a route prefix is configured, the page's when
/// `paginate`, and `sort` when `sort` lists the keys it takes.
struct ToolSchema<'a> {
    base: &'a str,
    config: &'a Config,
    paginate: bool,
    sort: Option<&'a [String]>,
}

/// One entry of the tool registry. The handler's own bindings are
/// `ontogen_`-prefixed so an argument bound under its fn param's name
/// (`state`, `store`, `limit`, ...) cannot shadow them.
///
/// The input schema names every argument the tool reads, so the handler
/// first refuses an argument it does not name, which would otherwise be
/// silently ignored, as HTTP refuses an unknown member.
fn push_tool(out: &mut String, tool_name: &str, desc: &str, schema: &ToolSchema, body: &str) {
    let schema_fn = tool_schema_fn(schema);
    let schema_value = tool_schema_value(schema);
    out.push_str(&format!(
        "\
        McpToolDef {{
            name: \"{tool_name}\",
            description: \"{desc}\",
            schema_fn: {schema_fn},
            handler: |ontogen_state, ontogen_args| {{
                Box::pin(async move {{
                    refuse_unknown_args(ontogen_args, {schema_value})?;
{body}                }})
            }},
        }},
"
    ));
}

/// The tool's input schema as an expression: `base` (a `schema_for::<T>`
/// path) called, with the scope's argument when a route prefix is
/// configured, the page's when the tool reads one, and `sort` when it reads
/// that.
fn tool_schema_value(schema: &ToolSchema<'_>) -> String {
    let mut value = format!("{}()", schema.base);
    if schema.config.route_prefix.is_some() {
        value = format!("with_project_id_schema({value})");
    }
    if schema.paginate {
        value = format!("with_pagination_schema({value})");
    }
    if let Some(keys) = schema.sort {
        let keys: Vec<String> = keys.iter().map(|k| format!("\"{k}\"")).collect();
        value = format!("with_sort_schema({value}, &[{}])", keys.join(", "));
    }
    value
}

/// The registry's `schema_fn` for [`tool_schema_value`]: `base` itself when
/// nothing is added to it, else a closure.
fn tool_schema_fn(schema: &ToolSchema<'_>) -> String {
    if schema.config.route_prefix.is_none() && !schema.paginate && schema.sort.is_none() {
        schema.base.to_string()
    } else {
        format!("|| {}", tool_schema_value(schema))
    }
}

/// The sort keys a list tool's `sort` argument takes, from the entity its
/// module serves, in the order the store's `{Entity}SortField` declares
/// them (ADR 0006 §2). `None` for a list that takes no order.
fn list_sort_keys(m: &ApiModule, f: &ApiFn, config: &Config) -> Option<Vec<String>> {
    if !f.takes_order() {
        return None;
    }
    let resource = config.resources.by_module(&m.name)?;
    Some(sort_keys(&sort_fields(&resource.entity, &config.enums)))
}

/// Refuses a sorted list whose bare filter is named `sort`: the list tool
/// reads its sort keys from the argument `sort`, so the two would share one
/// key.
pub(crate) fn check_sort_key(modules: &[ApiModule], config: &Config) -> Result<(), String> {
    for m in modules {
        for f in m.functions.iter().filter(|f| classify_op(m, f) == OpKind::List && f.takes_order()) {
            if f.bare_filters().iter().any(|p| p.name == "sort") {
                let tool = crate::servers::generators::ipc::command_name(&m.name, f, config);
                return Err(format!(
                    "ontogen: the MCP tool `{tool}` cannot be generated: `{}::{}` takes a filter named `sort`, \
                     which is the argument the tool itself reads its sort keys from, so the two would share one \
                     key. Rename the argument.",
                    m.name, f.name
                ));
            }
        }
    }
    Ok(())
}

/// Refuses, under a route prefix, a fn whose MCP tool would read an
/// argument under the prefix parameter's name (`project_id`). Every scoped
/// tool reads that argument itself to pick the store, so the op's own
/// argument and the scope would share one key. The keys checked are the
/// ones a tool reads by name: `id` for get, update and delete, each bare
/// filter of a list and `sort` when it takes an order, and each parameter
/// of a custom op or junction tool
/// (other than an `*Input` taken as the whole argument object). The fields
/// of an `*Input` or `*Query` struct read flat are not known here.
pub(crate) fn check_scope_key(modules: &[ApiModule], config: &Config) -> Result<(), String> {
    let Some(scope) = scope_key(config) else {
        return Ok(());
    };
    for m in modules {
        for f in &m.functions {
            let keys: Vec<&str> = match classify_op(m, f) {
                OpKind::GetById | OpKind::Update | OpKind::Delete => vec!["id"],
                OpKind::Create | OpKind::EventStream => vec![],
                OpKind::List => f
                    .bare_filters()
                    .into_iter()
                    .map(|p| p.name.as_str())
                    .chain(f.takes_order().then_some("sort"))
                    .collect(),
                _ if sole_body_param(f).is_some() => vec![],
                _ => f.params.iter().map(|p| p.name.as_str()).collect(),
            };
            if keys.contains(&scope.as_str()) {
                let tool = crate::servers::generators::ipc::command_name(&m.name, f, config);
                return Err(format!(
                    "ontogen: the MCP tool `{tool}` cannot be generated: `{}::{}` takes an argument named `{scope}`, \
                     which is the argument the tool itself reads for the route prefix parameter, so the two would \
                     share one key. Rename the argument.",
                    m.name, f.name
                ));
            }
        }
    }
    Ok(())
}

/// The argument naming the scope, which the handler prefix reads itself.
fn scope_key(config: &Config) -> Option<String> {
    config.route_prefix.as_ref().map(|prefix| prefix.params[0].name.clone())
}

/// The keys a list tool reads itself, beside its `*Query` struct: each
/// bare filter, `sort` when it takes an order, the page when it reads one,
/// and the scope. The struct is read from the other arguments, so one that
/// refuses unknown fields accepts a call that sends them, and a struct
/// field serialized as `sort` is never read from a sorted list's arguments.
fn list_struct_skipped_keys(f: &ApiFn, config: &Config, paginate: bool) -> Vec<String> {
    let mut keys: Vec<String> = f.bare_filters().iter().map(|p| p.name.clone()).collect();
    if f.takes_order() {
        keys.push("sort".to_string());
    }
    if paginate {
        keys.extend(["limit".to_string(), "offset".to_string()]);
    }
    keys.extend(scope_key(config));
    keys
}

/// The value a struct is deserialized from: the tool's arguments without
/// `skipped`.
fn struct_args(skipped: &[String]) -> String {
    if skipped.is_empty() {
        return "ontogen_args.clone()".to_string();
    }
    let keys: Vec<String> = skipped.iter().map(|k| format!("\"{k}\"")).collect();
    format!("args_without(ontogen_args, &[{}])", keys.join(", "))
}

/// The struct whose schema is a filtered list's tool input:
/// `Ontogen{Module}{Fn}Filter`, a name no imported user type takes.
fn list_filter_schema_name(m: &ApiModule, f: &ApiFn) -> String {
    format!("Ontogen{}{}Filter", to_pascal_case(&m.name), to_pascal_case(&f.name))
}

/// The schema-only struct of a list's filter: each bare filter as its owned
/// type, so an `Option` one is optional and any other required, with the
/// `*Query` struct's fields flattened beside them. The handler reads each
/// argument on its own; this struct only describes them.
fn list_filter_schema_struct(m: &ApiModule, f: &ApiFn) -> String {
    let mut out = format!(
        "/// The arguments the `{}` list tool reads as its filter.\n#[derive(JsonSchema)]\npub struct {} {{\n",
        m.name,
        list_filter_schema_name(m, f)
    );
    for p in f.bare_filters() {
        out.push_str(&format!("    pub {}: {},\n", p.name, param_to_owned_type(&p.ty_ast)));
    }
    if let Some(qp) = f.filter_struct() {
        out.push_str(&format!("    #[serde(flatten)]\n    pub ontogen_query: {},\n", extract_input_type(&qp.ty)));
    }
    out.push_str("}\n\n");
    out
}

/// A custom op's one parameter when it is an `*Input` struct: the tool's
/// arguments are that struct's fields. Beside other parameters it is one
/// argument among them, named as its parameter, as on IPC, so its fields
/// cannot collide with theirs.
fn sole_body_param(f: &ApiFn) -> Option<&Param> {
    match f.params.as_slice() {
        [p] if p.ty.contains("Input") => Some(p),
        _ => None,
    }
}

/// The struct whose schema is a custom op's tool input:
/// `Ontogen{Module}{Fn}Input`, a name no imported user type takes.
fn generic_input_schema_name(m: &ApiModule, f: &ApiFn) -> String {
    format!("Ontogen{}{}Input", to_pascal_case(&m.name), to_pascal_case(&f.name))
}

/// The schema-only struct of a custom op's arguments, each parameter as
/// its owned type. `None` for an op that takes no parameter or only an
/// `*Input` body, whose schema is the body's own.
fn generic_input_schema_struct(m: &ApiModule, f: &ApiFn) -> Option<String> {
    if f.params.is_empty() || sole_body_param(f).is_some() {
        return None;
    }
    let mut out = format!(
        "/// The arguments of the `{}` tool.\n#[derive(JsonSchema)]\npub struct {} {{\n",
        f.name,
        generic_input_schema_name(m, f)
    );
    for p in &f.params {
        out.push_str(&format!("    pub {}: {},\n", p.name, param_to_owned_type(&p.ty_ast)));
    }
    out.push_str("}\n\n");
    Some(out)
}

/// The lines reading the argument `p` from a tool's `ontogen_args`, bound
/// under its name: a `&str` borrowed with `required_str`, any other type
/// deserialized as its owned type, optional when it is an `Option`. A
/// missing required argument or a value of the wrong type is the tool's
/// error.
fn arg_extraction(p: &Param) -> String {
    let name = &p.name;
    if p.ty == "&str" {
        return format!("                    let {name} = required_str(ontogen_args, \"{name}\")?;\n");
    }
    let owned = param_to_owned_type(&p.ty_ast);
    let invalid = format!(".map_err(|e| format!(\"Invalid parameter {name}: {{e}}\"))?");
    match owned.strip_prefix("Option<").and_then(|t| t.strip_suffix('>')) {
        Some(inner) => format!(
            "                    let {name}: {owned} = ontogen_args.get(\"{name}\").filter(|v| !v.is_null()).cloned().map(serde_json::from_value::<{inner}>).transpose(){invalid};\n"
        ),
        None => format!(
            "                    let {name}: {owned} = serde_json::from_value(ontogen_args.get(\"{name}\").cloned().ok_or(\"Missing required parameter: {name}\")?){invalid};\n"
        ),
    }
}
