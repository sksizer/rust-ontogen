//! Generate MCP (Model Context Protocol) tool registry from API modules.

use std::fs;
use std::path::Path;

use ontogen_core::ir::OpKind;

use crate::schema::sort::{sort_fields, sort_keys};
use crate::servers::classify::classify_op;
use crate::servers::config::{Config, PaginationConfig};
use crate::servers::generators::{filter_arg, surface_use_stmts};
use crate::servers::parse::{ApiFn, ApiModule, Param};
use crate::servers::types::{extract_input_type, forward_arg_expr, param_to_owned_type, to_pascal_case};

/// Returns handler prefix code that extracts and validates project_id from MCP args.
fn mcp_handler_prefix(config: &Config) -> String {
    match &config.route_prefix {
        Some(prefix) => {
            let pp = &prefix.params[0];
            let accessor = &prefix.state_accessor;
            format!(
                "\
                    if let Some(pid) = ontogen_args.get(\"{}\").and_then(|v| v.as_str()) {{
                        let uuid = uuid::Uuid::parse_str(pid).map_err(|e| e.to_string())?;
                        ontogen_state.{}(&uuid).map_err(|e| e.to_string())?;
                    }}
",
                pp.name, accessor,
            )
        }
        None => String::new(),
    }
}

/// Returns Store construction code for a store-based MCP handler.
///
/// Extracts optional project_id from args and constructs the Store via the
/// prefix accessor; otherwise opens it through the fn's surface accessor.
fn mcp_store_construction(config: &Config, f: &ApiFn) -> String {
    let store_accessor = &f.store_accessor;
    match &config.route_prefix {
        Some(prefix) => {
            let pp = &prefix.params[0];
            let accessor = &prefix.state_accessor;
            format!(
                "\
                    let ontogen_store = if let Some(pid) = ontogen_args.get(\"{}\").and_then(|v| v.as_str()) {{
                        let uuid = uuid::Uuid::parse_str(pid).map_err(|e| e.to_string())?;
                        ontogen_state.{}(&uuid).map_err(|e| e.to_string())?
                    }} else {{
                        ontogen_state.{store_accessor}().await.map_err(|e| e.to_string())?
                    }};
",
                pp.name, accessor,
            )
        }
        None => {
            format!(
                "                    let ontogen_store = ontogen_state.{store_accessor}().await.map_err(|e| e.to_string())?;\n"
            )
        }
    }
}

/// Generate MCP tool registry and write to the output file.
pub fn generate(output: &Path, modules: &[ApiModule], config: &Config) {
    let mut out = String::new();
    let state_type = &config.state_type;

    out.push_str(
        "\
#![allow(dead_code, unused_imports, unused_variables, clippy::pedantic, clippy::needless_borrow)]
//! Auto-generated MCP tool registry. DO NOT EDIT.
//!
//! Generated by ontogen from API source files.

use std::future::Future;
use std::pin::Pin;

use schemars::JsonSchema;
use serde::Deserialize;
use serde_json::{json, Value};

",
    );

    for stmt in surface_use_stmts(modules, config) {
        out.push_str(&stmt);
    }

    out.push_str(&format!("use {};\n", config.state_import));

    // Add Store import if store_type is configured
    if let Some(ref store_import) = config.store_import {
        out.push_str(&format!("use {};\n", store_import));
    }

    out.push('\n');

    out.push_str(&format!(
        "\
/// Async handler signature for MCP tools.
type HandlerFn = for<'a> fn(
    &'a {state_type},
    &'a Value,
) -> Pin<Box<dyn Future<Output = Result<Value, String>> + Send + 'a>>;

/// A single MCP tool definition.
pub struct McpToolDef {{
    pub name: &'static str,
    pub description: &'static str,
    pub schema_fn: fn() -> Value,
    pub handler: HandlerFn,
}}

fn schema_for<T: JsonSchema>() -> Value {{
    serde_json::to_value(schemars::schema_for!(T)).expect(\"schemars schema must serialize\")
}}

fn schema_for_with_str_id<T: JsonSchema>() -> Value {{
    let mut schema = schema_for::<T>();
    if let Some(obj) = schema.as_object_mut() {{
        if let Some(props) = obj.get_mut(\"properties\").and_then(|p| p.as_object_mut()) {{
            props.insert(\"id\".to_string(), json!({{\"type\": \"string\"}}));
        }}
        if let Some(req) = obj.get_mut(\"required\").and_then(|r| r.as_array_mut()) {{
            req.push(json!(\"id\"));
        }} else {{
            obj.insert(\"required\".to_string(), json!([\"id\"]));
        }}
    }}
    schema
}}

#[allow(dead_code)]
fn schema_for_with_int_id<T: JsonSchema>() -> Value {{
    let mut schema = schema_for::<T>();
    if let Some(obj) = schema.as_object_mut() {{
        if let Some(props) = obj.get_mut(\"properties\").and_then(|p| p.as_object_mut()) {{
            props.insert(\"id\".to_string(), json!({{\"type\": \"integer\", \"format\": \"int32\"}}));
        }}
        if let Some(req) = obj.get_mut(\"required\").and_then(|r| r.as_array_mut()) {{
            req.push(json!(\"id\"));
        }} else {{
            obj.insert(\"required\".to_string(), json!([\"id\"]));
        }}
    }}
    schema
}}

/// The string argument `key`: missing is one error, any other type another.
/// A value of another type is worded as serde words it for a `String`
/// (`expected a string`), not for a `&str` (`expected a borrowed string`).
fn required_str<'a>(args: &'a Value, key: &str) -> Result<&'a str, String> {{
    let value = args.get(key).ok_or_else(|| format!(\"Missing required parameter: {{key}}\"))?;
    value.as_str().ok_or_else(|| {{
        let e = String::deserialize(value).expect_err(\"a value that is no string is no String\");
        format!(\"Invalid parameter {{key}}: {{e}}\")
    }})
}}

/// `args` without the keys a tool reads on its own: the rest is the struct
/// it deserializes, which may refuse a field it does not declare.
fn args_without(args: &Value, keys: &[&str]) -> Value {{
    let mut rest = args.clone();
    if let Some(rest) = rest.as_object_mut() {{
        for key in keys {{
            rest.remove(*key);
        }}
    }}
    rest
}}

/// Refuses an argument the tool's input schema does not name, so a
/// misspelt argument is an error rather than one silently dropped (a
/// misspelt filter is not a wider list). A schema that leaves its object
/// open (an `additionalProperties` other than `false`) or composes it
/// (`allOf`, `anyOf`, `oneOf`, `$ref`) names no closed set of arguments, so
/// it refuses none.
fn refuse_unknown_args(args: &Value, schema: Value) -> Result<(), String> {{
    let open = schema.get(\"additionalProperties\").is_some_and(|a| a != &Value::Bool(false))
        || [\"allOf\", \"anyOf\", \"oneOf\", \"$ref\"].iter().any(|k| schema.get(*k).is_some());
    if open {{
        return Ok(());
    }}
    let named = schema.get(\"properties\").and_then(Value::as_object);
    let unknown = args.as_object().and_then(|args| args.keys().find(|key| !named.is_some_and(|n| n.contains_key(*key))));
    match unknown {{
        Some(key) => Err(format!(\"Unknown argument: {{key}}\")),
        None => Ok(()),
    }}
}}

/// Input for tools that look up a resource by string ID.
#[derive(Deserialize, JsonSchema)]
pub struct GetByIdInput {{
    pub id: String,
}}

/// Input for tools that operate on an integer id (i32).
#[derive(Deserialize, JsonSchema)]
pub struct ByIntIdInput {{
    pub id: i32,
}}

/// An empty-object schema for tools that take no parameters.
#[derive(Deserialize, JsonSchema)]
pub struct EmptyInput {{}}

",
    ));

    // Add project_id schema helper when route_prefix is configured
    if let Some(prefix) = &config.route_prefix {
        let pp = &prefix.params[0];
        out.push_str(&format!(
            "\
/// Inject an optional `{pp_name}` property into a JSON schema.
fn with_project_id_schema(mut schema: Value) -> Value {{
    if let Some(obj) = schema.as_object_mut() {{
        let props = obj.entry(\"properties\").or_insert_with(|| json!({{}}));
        if let Some(props_obj) = props.as_object_mut() {{
            props_obj.insert(\"{pp_name}\".to_string(), json!({{
                \"type\": \"string\",
                \"format\": \"uuid\",
                \"description\": \"Project ID (optional - uses default project if omitted)\"
            }}));
        }}
    }}
    schema
}}

",
            pp_name = pp.name,
        ));
    }

    // Add pagination schema helper when pagination is configured
    if config.any_pagination() {
        out.push_str(
            "\
/// Inject `limit` and `offset` pagination properties into a JSON schema.
fn with_pagination_schema(mut schema: Value) -> Value {
    if let Some(obj) = schema.as_object_mut() {
        let props = obj.entry(\"properties\").or_insert_with(|| json!({}));
        if let Some(props_obj) = props.as_object_mut() {
            props_obj.insert(\"limit\".to_string(), json!({
                \"type\": \"integer\",
                \"description\": \"Maximum number of items to return\"
            }));
            props_obj.insert(\"offset\".to_string(), json!({
                \"type\": \"integer\",
                \"description\": \"Number of items to skip\"
            }));
        }
    }
    schema
}

",
        );
    }

    if modules.iter().any(|m| m.functions.iter().any(|f| classify_op(m, f) == OpKind::List && f.takes_order())) {
        out.push_str(SORT_HELPERS);
    }

    // A custom op's input schema names each plain parameter beside its
    // body's fields, so the tool advertises every argument it reads.
    for m in modules {
        for f in &m.functions {
            let op = classify_op(m, f);
            if !matches!(
                op,
                OpKind::CustomGet
                    | OpKind::CustomPost
                    | OpKind::JunctionList { .. }
                    | OpKind::JunctionAdd { .. }
                    | OpKind::JunctionRemove { .. }
            ) {
                continue;
            }
            out.push_str(&generic_input_schema_struct(m, f).unwrap_or_default());
        }
    }

    // A list's input schema names each bare filter beside its `*Query`
    // struct's fields, so the tool advertises every argument it reads.
    for m in modules {
        for f in &m.functions {
            if classify_op(m, f) == OpKind::List && !f.bare_filters().is_empty() {
                out.push_str(&list_filter_schema_struct(m, f));
            }
        }
    }

    let hp = mcp_handler_prefix(config);

    out.push_str(
        "/// Generated MCP tool definitions.\npub fn generated_tool_registry() -> Vec<McpToolDef> {\n    vec![\n",
    );

    for m in modules {
        if m.functions.is_empty() {
            continue;
        }

        let module = &m.name;

        for f in &m.functions {
            // Use the canonical entity-first command name for tool names
            let tool_name = crate::servers::generators::ipc::command_name(module, f, config);
            let op = classify_op(m, f);
            let svc = m.service_ident(f.surface);
            let is_async = f.is_async;
            let desc = if f.doc.is_empty() { format!("{} {}", f.name, module) } else { f.doc.clone() };
            let sc = mcp_store_construction(config, f);
            let (prefix, first_arg) =
                if f.first_param_is_store { (sc.as_str(), "&ontogen_store") } else { (hp.as_str(), "ontogen_state") };

            match op {
                OpKind::List => {
                    let await_str = if is_async { ".await" } else { "" };
                    let ret_type = &f.return_type;
                    // Pagination only applies when the list function returns Vec<T>;
                    // custom result types (e.g., CodingAgentListResult) are passed through unchanged.
                    let pagination = config.pagination_for(module, f.surface).filter(|_| ret_type.starts_with("Vec<"));
                    let paginate = pagination.is_some();
                    // A pushed-down list's own limit/offset are the page, taken
                    // from `args` below — not tool arguments to extract.
                    let pushes_page = paginate && f.takes_page();
                    let schema_input = match f.filter_struct() {
                        _ if !f.bare_filters().is_empty() => list_filter_schema_name(m, f),
                        Some(qp) => extract_input_type(&qp.ty),
                        None => "EmptyInput".to_string(),
                    };
                    let schema_base = format!("schema_for::<{schema_input}>");
                    let mut extraction = String::new();
                    if let Some(qp) = f.filter_struct() {
                        let qt = extract_input_type(&qp.ty);
                        let rest = struct_args(&list_struct_skipped_keys(f, config, paginate));
                        extraction.push_str(&format!(
                            "                    let ontogen_filter: {qt} = serde_json::from_value({rest}).map_err(|e| format!(\"Invalid filter: {{e}}\"))?;\n"
                        ));
                    }
                    for pp in f.bare_filters() {
                        extraction.push_str(&arg_extraction(pp));
                    }
                    // A list that takes an order reads it from `sort` after its
                    // filter, as HTTP does, and passes it after the filter.
                    let order_arg = if f.takes_order() {
                        extraction.push_str(ORDER_FROM_SORT);
                        ", &ontogen_order"
                    } else {
                        ""
                    };
                    // A filtered page calls `count` with the same filter after
                    // `list`, which gets a clone of whatever it would consume.
                    let filter_args = |counted: bool| -> String {
                        f.filter()
                            .iter()
                            .map(|p| match p.ty.as_str() {
                                _ if p.is_filter_struct() => format!(", {}", filter_arg(p, "ontogen_filter", counted)),
                                // `required_str` already lends a `&str`.
                                "&str" => format!(", {}", p.name),
                                _ => format!(", {}", filter_arg(p, &p.name, counted)),
                            })
                            .collect()
                    };
                    let count_args = filter_args(false);
                    let extra_args = format!("{count_args}{order_arg}");
                    let body = if let Some(pg) = pagination {
                        let default_limit = pg.default_limit;
                        let max_limit = pg.max_limit;
                        // Two shapes. When `list` takes the page it is pushed down
                        // and the total comes from the module's `count` — nothing
                        // beyond the page is ever materialised. A list that does not
                        // take it (not every Vec-returning op is the checked `list`)
                        // keeps the older in-memory slice.
                        // A filtered page calls `count` with the same filter,
                        // after `list` has consumed it.
                        let read = if pushes_page {
                            let list_args = format!("{}{order_arg}", filter_args(true));
                            format!(
                                "\
                    let ontogen_limit = ontogen_args.get(\"limit\").and_then(|v| v.as_u64()).unwrap_or({default_limit}).min({max_limit});
                    let ontogen_offset = ontogen_args.get(\"offset\").and_then(|v| v.as_u64()).unwrap_or(0);
                    let ontogen_items = {svc}::list({first_arg}{list_args}, Some(ontogen_limit), Some(ontogen_offset)){await_str}.map_err(|e| e.to_string())?;
                    let ontogen_total = {svc}::count({first_arg}{count_args}){await_str}.map_err(|e| e.to_string())?;
"
                            )
                        } else {
                            format!(
                                "                    let ontogen_all = {svc}::list({first_arg}{extra_args}){await_str}.map_err(|e| e.to_string())?;\n{}",
                                in_memory_page(default_limit, max_limit)
                            )
                        };
                        format!("{prefix}{read}{PAGE_RESULT}")
                    } else {
                        // A surface with no pagination passes no page, so a list that takes one gets the whole table.
                        let page_args = if f.takes_page() { ", None, None" } else { "" };
                        format!(
                            "\
{prefix}                    let ontogen_items = {svc}::list({first_arg}{extra_args}{page_args}){await_str}.map_err(|e| e.to_string())?;
                    serde_json::to_value(ontogen_items).map_err(|e| format!(\"Serialize error: {{e}}\"))
"
                        )
                    };
                    let sort = list_sort_keys(m, f, config);
                    let schema = ToolSchema { base: &schema_base, config, paginate, sort: sort.as_deref() };
                    push_tool(&mut out, &tool_name, &desc, &schema, &format!("{extraction}{body}"));
                }

                OpKind::GetById => {
                    let await_str = if is_async { ".await" } else { "" };
                    let fn_name = &f.name;
                    let schema = ToolSchema { base: "schema_for::<GetByIdInput>", config, paginate: false, sort: None };
                    let body = format!(
                        "\
{prefix}                    let id = required_str(ontogen_args, \"id\")?;
                    let item = {svc}::{fn_name}({first_arg}, id){await_str}.map_err(|e| e.to_string())?;
                    serde_json::to_value(item).map_err(|e| format!(\"Serialize error: {{e}}\"))
"
                    );
                    push_tool(&mut out, &tool_name, &desc, &schema, &body);
                }

                OpKind::Create => {
                    let input_type = extract_input_type(&f.params[0].ty);
                    let await_str = if is_async { ".await" } else { "" };
                    let schema_base = format!("schema_for::<{input_type}>");
                    let schema = ToolSchema { base: &schema_base, config, paginate: false, sort: None };
                    let rest = struct_args(&scope_key(config).into_iter().collect::<Vec<_>>());
                    let body = format!(
                        "\
{prefix}                    let input: {input_type} = serde_json::from_value({rest})
                        .map_err(|e| format!(\"Invalid input: {{e}}\"))?;
                    {svc}::create({first_arg}, input){await_str}.map_err(|e| e.to_string())?;
                    Ok(json!({{\"success\": true}}))
"
                    );
                    push_tool(&mut out, &tool_name, &desc, &schema, &body);
                }

                OpKind::Update => {
                    let input_type = extract_input_type(&f.params[1].ty);
                    let await_str = if is_async { ".await" } else { "" };
                    let schema_base = format!("schema_for_with_str_id::<{input_type}>");
                    let schema = ToolSchema { base: &schema_base, config, paginate: false, sort: None };
                    let rest =
                        struct_args(&["id".to_string()].into_iter().chain(scope_key(config)).collect::<Vec<_>>());
                    let body = format!(
                        "\
{prefix}                    let id = required_str(ontogen_args, \"id\")?.to_string();
                    let input: {input_type} = serde_json::from_value({rest})
                        .map_err(|e| format!(\"Invalid input: {{e}}\"))?;
                    {svc}::update({first_arg}, &id, input){await_str}.map_err(|e| e.to_string())?;
                    Ok(json!({{\"success\": true}}))
"
                    );
                    push_tool(&mut out, &tool_name, &desc, &schema, &body);
                }

                OpKind::Delete => {
                    let await_str = if is_async { ".await" } else { "" };
                    let schema = ToolSchema { base: "schema_for::<GetByIdInput>", config, paginate: false, sort: None };
                    let body = format!(
                        "\
{prefix}                    let id = required_str(ontogen_args, \"id\")?.to_string();
                    {svc}::delete({first_arg}, &id){await_str}.map_err(|e| e.to_string())?;
                    Ok(json!({{\"success\": true}}))
"
                    );
                    push_tool(&mut out, &tool_name, &desc, &schema, &body);
                }

                OpKind::JunctionList { .. } => {
                    generate_generic_mcp_tool(&mut out, m, f, config, true);
                }

                OpKind::JunctionAdd { .. } | OpKind::JunctionRemove { .. } => {
                    generate_generic_mcp_tool(&mut out, m, f, config, false);
                }

                OpKind::CustomGet | OpKind::CustomPost => {
                    generate_generic_mcp_tool(&mut out, m, f, config, false);
                }

                // Event ops are skipped: an MCP tool call returns one result
                // and has no shape for a subscription.
                OpKind::EventStream => continue,
            }
        }
    }

    out.push_str("    ]\n}\n\n");

    // Generate simple tool_definitions() that returns static schema data
    out.push_str(&format!(
        "\
/// Simple tool definition with pre-computed schema (for MCP protocol responses).
pub struct SimpleToolDef {{
    pub name: &'static str,
    pub description: &'static str,
    pub input_schema: Value,
}}

/// Return tool definitions with pre-computed input schemas.
/// Use this for building MCP `tools/list` responses.
pub fn tool_definitions() -> Vec<SimpleToolDef> {{
    generated_tool_registry()
        .into_iter()
        .map(|t| SimpleToolDef {{
            name: t.name,
            description: t.description,
            input_schema: (t.schema_fn)(),
        }})
        .collect()
}}

/// Dispatch a tool call by name, executing the matching handler synchronously.
///
/// This creates a minimal tokio runtime to drive the async handler.
/// Suitable for MCP servers that process requests synchronously.
pub fn handle_tool_call(
    state: &{state_type},
    tool_name: &str,
    args: &serde_json::Map<String, Value>,
) -> Result<Value, String> {{
    let registry = generated_tool_registry();
    let tool = registry
        .iter()
        .find(|t| t.name == tool_name)
        .ok_or_else(|| format!(\"Unknown tool: {{tool_name}}\"))?;
    let args_value = Value::Object(args.clone());
    let rt = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(|e| format!(\"Runtime error: {{e}}\"))?;
    rt.block_on((tool.handler)(state, &args_value))
}}
"
    ));

    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).expect("Failed to create output directory");
    }
    crate::write_and_format(output, out).expect("Failed to write MCP generated file");
}

fn generate_generic_mcp_tool(out: &mut String, m: &ApiModule, f: &ApiFn, config: &Config, is_list_op: bool) {
    let module = m.name.as_str();
    let svc = m.service_ident(f.surface);
    let fn_name = &f.name;
    let desc = if f.doc.is_empty() { fn_name.clone() } else { f.doc.clone() };
    let await_str = if f.is_async { ".await" } else { "" };
    let tool_name = crate::servers::generators::ipc::command_name(module, f, config);
    // Pagination only applies to list operations that return Vec<T>;
    // custom result types are passed through unchanged.
    let pagination: Option<&PaginationConfig> =
        config.pagination_for(module, f.surface).filter(|_| is_list_op && f.return_type.starts_with("Vec<"));
    // Stateless tools skip the state/store handler prefix and forward no
    // positional state argument to the service function. The MCP runtime
    // still hands `ontogen_state` and `ontogen_args` to every tool handler
    // closure — the body just doesn't reference the state.
    let (hp, first_arg) = if f.is_stateless {
        (String::new(), None)
    } else if f.first_param_is_store {
        (mcp_store_construction(config, f), Some("&ontogen_store"))
    } else {
        (mcp_handler_prefix(config), Some("ontogen_state"))
    };

    let body = sole_body_param(f);
    let schema_input = match (body, f.params.is_empty()) {
        (Some(body), _) => extract_input_type(&body.ty),
        (None, true) => "EmptyInput".to_string(),
        (None, false) => generic_input_schema_name(m, f),
    };
    let schema_base = format!("schema_for::<{schema_input}>");
    let schema = ToolSchema { base: &schema_base, config, paginate: pagination.is_some(), sort: None };

    let mut extraction = String::new();
    let mut call_args: Vec<String> = first_arg.map(str::to_string).into_iter().collect();
    if let Some(body) = body {
        // A body alone is the arguments themselves, less the scope's.
        let skipped: Vec<String> = if f.is_stateless { Vec::new() } else { scope_key(config).into_iter().collect() };
        extraction.push_str(&format!(
            "                    let ontogen_input: {} = serde_json::from_value({})\n                        .map_err(|e| format!(\"Invalid input: {{e}}\"))?;\n",
            extract_input_type(&body.ty),
            struct_args(&skipped)
        ));
        call_args.push(forward_arg_expr("ontogen_input", &body.ty_ast));
    } else {
        for p in &f.params {
            extraction.push_str(&arg_extraction(p));
            // `required_str` already lends a `&str`.
            call_args.push(if p.ty == "&str" { p.name.clone() } else { forward_arg_expr(&p.name, &p.ty_ast) });
        }
    }
    let call = format!("{svc}::{fn_name}({}){await_str}.map_err(|e| e.to_string())?", call_args.join(", "));

    let result = if f.return_type == "()" {
        format!("                    {call};\n                    Ok(json!({{\"success\": true}}))\n")
    } else if let Some(pg) = pagination {
        format!(
            "                    let ontogen_all = {call};\n{}{PAGE_RESULT}",
            in_memory_page(pg.default_limit, pg.max_limit)
        )
    } else {
        format!(
            "                    let ontogen_result = {call};\n                    serde_json::to_value(ontogen_result).map_err(|e| format!(\"Serialize error: {{e}}\"))\n"
        )
    };
    push_tool(out, &tool_name, &desc, &schema, &format!("{extraction}{hp}{result}"));
}

