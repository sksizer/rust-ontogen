#![allow(clippy::too_many_lines, clippy::format_push_string)]

//! Generate TypeScript HTTP client from API modules.

use std::fs;
use std::path::Path;

use crate::clients::config::Config;
use crate::clients::generators::jsonapi;
use crate::clients::generators::{FallbackRecord, command_name};
use crate::servers::parse::ApiModule;
use crate::servers::types::{collect_ts_import, extract_input_type, rust_type_to_ts, snake_to_camel};

/// Generate TypeScript HTTP client and write to the output file.
///
/// Returns a [`FallbackRecord`] for every type referenced by the generated TS
/// surface that wasn't exported from `bindings.ts` and therefore had to be
/// stubbed as `Record<string, unknown>`. (OF-006)
pub fn generate(output: &Path, bindings_path: &Path, modules: &[ApiModule], config: &Config) -> Vec<FallbackRecord> {
    let mut out = String::new();

    // Read bindings.ts to discover which types are actually exported
    let bindings_content = fs::read_to_string(bindings_path).unwrap_or_default();
    let exported_types: Vec<String> = bindings_content
        .lines()
        .filter_map(|line| {
            line.strip_prefix("export type ")
                .and_then(|rest| rest.split(|c: char| !c.is_alphanumeric() && c != '_').next().map(|s| s.to_string()))
        })
        .collect();

    out.push_str(
        "// Auto-generated HTTP client. DO NOT EDIT.\n\
         // Generated by ontogen from API source files.\n\n",
    );

    // Collect all types we need to import
    let mut import_types: Vec<String> = Vec::new();

    for m in modules {
        if m.functions.is_empty() {
            continue;
        }
        for f in &m.functions {
            let cmd_name = command_name(&m.name, f, config);
            if cmd_name.is_empty() || config.ts_skip_commands.contains(&cmd_name) {
                continue;
            }
            let ts_ret = rust_type_to_ts(&f.return_type);
            collect_ts_import(&ts_ret, &mut import_types);
            for p in &f.params {
                let ty = extract_input_type(&p.ty);
                let ts_ty = rust_type_to_ts(&ty);
                collect_ts_import(&ts_ty, &mut import_types);
            }
        }
    }

    // Each flattener returns its entity type, whichever methods use it.
    let resources = jsonapi::served_resources(modules, config, false);
    for r in &resources {
        collect_ts_import(&r.entity.name, &mut import_types);
    }

    import_types.sort();
    import_types.dedup();

    let (available, missing): (Vec<_>, Vec<_>) = import_types.iter().partition(|t| exported_types.contains(t));

    if !available.is_empty() {
        out.push_str("import type {\n");
        for t in &available {
            out.push_str(&format!("  {},\n", t));
        }
        out.push_str("} from './bindings';\n\n");
    }

    let fallbacks: Vec<FallbackRecord> = missing
        .iter()
        .map(|t| FallbackRecord {
            output: output.to_path_buf(),
            bindings_path: bindings_path.to_path_buf(),
            type_name: (*t).clone(),
        })
        .collect();

    for t in &missing {
        out.push_str(&format!(
            "// TODO: Type '{t}' not yet exported from bindings.ts - using placeholder\n\
             type {t} = Record<string, unknown>;\n\n"
        ));
    }

    if config.any_pagination() {
        out.push_str(jsonapi::PAGINATED_RESULT);
    }
    out.push_str(jsonapi::JSON_API_TYPES);
    out.push_str(&jsonapi::http_helpers());
    if !resources.is_empty() {
        out.push_str(jsonapi::RESOURCE_HELPERS);
        for r in &resources {
            out.push_str(&jsonapi::resource_codec(r));
        }
    }

    out.push_str("export const httpCommands = {\n");

    for m in modules {
        for f in &m.functions {
            let cmd_name = command_name(&m.name, f, config);
            if cmd_name.is_empty() || config.ts_skip_commands.contains(&cmd_name) {
                continue;
            }
            let Some(method) = jsonapi::method(m, f, config, None) else { continue };
            out.push_str(&format!(
                "  async {}({}): Promise<{}> {{\n    {}\n  }},\n\n",
                snake_to_camel(&cmd_name),
                method.params.join(", "),
                method.return_type,
                method.body.join("\n").replace('\n', "\n    "),
            ));
        }
    }

    out.push_str("};\n");

    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).expect("Failed to create output directory");
    }
    crate::write_and_format_ts(output, out, &config.ts_formatter).expect("Failed to write TS HTTP client");

    fallbacks
}
