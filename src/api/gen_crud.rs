//! Generate CRUD forwarding functions for one entity.
//!
//! Each generated module delegates to the Store methods:
//! - `list` → `store.list_{entities}(order, None, None)`, or
//!   `list_{entities}(order, limit, offset)` plus `count` →
//!   `store.count_{entities}()` for a paginated entity; either is left out
//!   when a hand-written module of the same name defines it (see
//!   [`Omissions`]). `order` is the caller's sort, `&[]` for the default
//!   id order (ADR 0006 §1)
//! - `get_by_id` → `store.get_{entity}(id)`
//! - `create` → `store.create_{entity}({Entity}::from(input))`
//! - `update` → `store.update_{entity}(id, {Entity}Update::from(input))`
//! - `delete` → `store.delete_{entity}(id)`

use super::Omissions;
use crate::ApiConfig;
use crate::ident::rust_ident;
use crate::schema::model::EntityDef;
use crate::store::helpers::{pluralize, to_snake_case};

/// Generate the complete API module source for one entity.
pub(super) fn generate_crud_module(entity: &EntityDef, config: &ApiConfig, omit: Omissions) -> String {
    let name = &entity.name;
    let snake = to_snake_case(name);
    let module = rust_ident(&snake);
    let plural = pluralize(&snake);
    let schema_path = &config.schema_module_path;

    let mut code = String::with_capacity(2048);

    code.push_str("//! Generated by ontogen. DO NOT EDIT.\n\n");

    // Imports - sorted to match rustfmt's ordering (sub-paths before parent-level imports)
    // Only the generated `list` names the order, and a hand-written `list`
    // replaces it.
    if !omit.list {
        code.push_str("use ontogen_core::order::OrderBy;\n\n");
    }
    code.push_str(&format!("use {schema_path}::AppError;\n"));
    code.push_str(&format!("use {schema_path}::{name};\n"));
    code.push_str(&format!("use {schema_path}::{{Create{name}Input, Update{name}Input}};\n"));
    if omit.list {
        code.push_str(&format!("use crate::store::{module}::{name}Update;\n"));
    } else {
        code.push_str(&format!("use crate::store::{module}::{{{name}SortField, {name}Update}};\n"));
    }
    code.push_str("use crate::store::Store;\n\n");
    code.push('\n');

    // list (+ count when paginated)
    let paginated = config.paginated.iter().any(|m| m == &snake);
    if !omit.list {
        if paginated {
            code.push_str(&format!("/// One page of {plural}\n"));
            code.push_str(&format!(
                "pub async fn list(store: &Store, order: &[OrderBy<{name}SortField>], limit: Option<u64>, offset: Option<u64>) -> Result<Vec<{name}>, AppError> {{\n"
            ));
            code.push_str(&format!("    store.list_{plural}(order, limit, offset).await\n"));
            code.push_str("}\n\n");
        } else {
            code.push_str(&format!("/// List all {plural}\n"));
            code.push_str(&format!(
                "pub async fn list(store: &Store, order: &[OrderBy<{name}SortField>]) -> Result<Vec<{name}>, AppError> {{\n"
            ));
            code.push_str(&format!("    store.list_{plural}(order, None, None).await\n"));
            code.push_str("}\n\n");
        }
    }
    if paginated && !omit.count {
        code.push_str(&format!("/// How many {plural} there are — the total behind a page of `list`\n"));
        code.push_str("pub async fn count(store: &Store) -> Result<u64, AppError> {\n");
        code.push_str(&format!("    store.count_{plural}().await\n"));
        code.push_str("}\n\n");
    }

    // get_by_id
    code.push_str(&format!("/// Get a single {snake} by ID\n"));
    code.push_str(&format!("pub async fn get_by_id(store: &Store, id: &str) -> Result<{name}, AppError> {{\n"));
    code.push_str(&format!("    store.get_{snake}(id).await\n"));
    code.push_str("}\n\n");

    // create
    code.push_str(&format!("/// Create a new {snake}\n"));
    code.push_str(&format!(
        "pub async fn create(store: &Store, input: Create{name}Input) -> Result<{name}, AppError> {{\n"
    ));
    // No binding named after the entity: `Match` would make it `match`, and
    // `Store` or `Input` would shadow a parameter.
    code.push_str(&format!("    store.create_{snake}({name}::from(input)).await\n"));
    code.push_str("}\n\n");

    // update
    code.push_str(&format!("/// Update an existing {snake}\n"));
    code.push_str(&format!(
        "pub async fn update(store: &Store, id: &str, input: Update{name}Input) -> Result<{name}, AppError> {{\n"
    ));
    code.push_str(&format!("    store.update_{snake}(id, {name}Update::from(input)).await\n"));
    code.push_str("}\n\n");

    // delete
    code.push_str(&format!("/// Delete a {snake} by ID\n"));
    code.push_str("pub async fn delete(store: &Store, id: &str) -> Result<(), AppError> {\n");
    code.push_str(&format!("    store.delete_{snake}(id).await\n"));
    code.push_str("}\n");

    code
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::model::{EntityDef, FieldDef, FieldRole, FieldType};

    fn make_role_entity() -> EntityDef {
        EntityDef {
            name: "Role".to_string(),
            directory: "role".to_string(),
            table: "roles".to_string(),
            type_name: "role".to_string(),
            prefix: "role".to_string(),
            id_strategy: None,
            fields: vec![
                FieldDef::new("id", FieldType::String, FieldRole::Id),
                FieldDef::new("body", FieldType::String, FieldRole::Body),
            ],
            doc: String::new(),
        }
    }

    fn make_config() -> ApiConfig {
        ApiConfig {
            output_dir: std::path::PathBuf::new(),
            exclude: vec![],
            scan_dirs: vec![],
            state_type: "AppState".to_string(),
            store_type: Some("Store".to_string()),
            schema_module_path: "crate::schema".to_string(),
            paginated: vec![],
        }
    }

    /// Syntax check: verify `generate_crud_module` emits a syntactically valid
    /// Rust source file.
    #[test]
    fn generated_code_is_valid_rust() {
        let config = make_config();
        let code = generate_crud_module(&make_role_entity(), &config, Omissions::default());
        syn::parse_file(&code).unwrap_or_else(|e| {
            panic!("api::gen_crud::generate_crud_module produced invalid Rust: {e}\n--- code ---\n{code}")
        });
    }

    #[test]
    fn a_paginated_entity_gets_a_paged_list_and_a_count() {
        let entity = EntityDef {
            name: "Workout".to_string(),
            directory: "workout".to_string(),
            table: "workouts".to_string(),
            type_name: "workout".to_string(),
            prefix: "workout".to_string(),
            id_strategy: None,
            fields: vec![FieldDef::new("id", FieldType::String, FieldRole::Id)],
            doc: String::new(),
        };
        let mut config = make_config();
        config.paginated = vec!["workout".to_string()];
        let code = generate_crud_module(&entity, &config, Omissions::default());
        assert!(code.contains(
            "pub async fn list(store: &Store, order: &[OrderBy<WorkoutSortField>], limit: Option<u64>, offset: Option<u64>) -> Result<Vec<Workout>, AppError>"
        ));
        assert!(code.contains("store.list_workouts(order, limit, offset).await"));
        assert!(code.contains("pub async fn count(store: &Store) -> Result<u64, AppError>"), "count takes no order");
        assert!(code.contains("store.count_workouts().await"));

        let plain = generate_crud_module(&entity, &make_config(), Omissions::default());
        assert!(plain.contains(
            "pub async fn list(store: &Store, order: &[OrderBy<WorkoutSortField>]) -> Result<Vec<Workout>, AppError>"
        ));
        assert!(plain.contains("store.list_workouts(order, None, None).await"));
        assert!(!plain.contains("fn count("));
    }

    #[test]
    fn the_sort_field_and_order_are_imported_beside_the_update() {
        let code = generate_crud_module(&make_role_entity(), &make_config(), Omissions::default());
        assert!(code.contains("use ontogen_core::order::OrderBy;"), "{code}");
        assert!(code.contains("use crate::store::role::{RoleSortField, RoleUpdate};"), "{code}");

        let omitted = generate_crud_module(&make_role_entity(), &make_config(), Omissions { list: true, count: false });
        assert!(!omitted.contains("OrderBy") && !omitted.contains("RoleSortField"), "a hand-written list: {omitted}");
        assert!(omitted.contains("use crate::store::role::RoleUpdate;"), "{omitted}");
    }

    /// No forwarder binds the record: an entity named after a keyword
    /// (`Match`) or after a parameter (`Store`, `Input`) would break it.
    #[test]
    fn forwarders_bind_nothing_after_the_entity() {
        for entity in crate::schema::hostile_entities() {
            let code = generate_crud_module(&entity, &make_config(), Omissions::default());
            syn::parse_file(&code).unwrap_or_else(|e| panic!("{}: invalid Rust: {e}\n{code}", entity.name));
            let name = &entity.name;
            let snake = to_snake_case(name);
            assert!(code.contains(&format!("store.create_{snake}({name}::from(input)).await")), "{code}");
            assert!(code.contains(&format!("store.update_{snake}(id, {name}Update::from(input)).await")), "{code}");
            assert!(!code.contains("let "), "{code}");
        }
        let r#match = crate::schema::hostile_entities().into_iter().find(|e| e.name == "Match").expect("Match");
        let code = generate_crud_module(&r#match, &make_config(), Omissions::default());
        assert!(code.contains("use crate::store::r#match::{MatchSortField, MatchUpdate};"), "{code}");
        assert!(super::super::generate_mod_rs(&["match".into()]).contains("pub mod r#match;"));
    }
}
